export function pick(list, seed) {
  if (!list.length) return '';
  const i = seed === undefined ? Math.floor(Math.random() * list.length) : Math.abs(seed) % list.length;
  return list[i];
}

export function fill(template, party) {
  return String(template)
    .replaceAll('{name}', party?.name || 'המפלגה שלנו')
    .replaceAll('{letters}', party?.acronym || 'אבג')
    .replaceAll('{slogan}', party?.slogan || 'קודם קפה, אחר כך מדיניות');
}
